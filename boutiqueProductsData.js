export function isBoutiqueProductAvailable(product) {
  if (!product) return false;
  if (product.soldOut === true) return false;
  const stock = Number(product.stock);
  return Number.isFinite(stock) ? stock > 0 : true;
}

export function formatBoutiquePrice(price) {
  return `$${Number(price).toFixed(2)}`;
}

/** Return gallery mockups for a product (falls back to primary image). */
export function getBoutiqueProductImages(product) {
  if (!product) return [];
  if (Array.isArray(product.imageUrls) && product.imageUrls.length) {
    return product.imageUrls.map((uri) => String(uri).trim()).filter(Boolean);
  }
  if (product.imageUrl) return [String(product.imageUrl).trim()];
  return [];
}

/**
 * Boutique catalog images are Shopify /files/ assets — keep source URLs intact.
 */
export function getBoutiqueThumbUrl(imageUrl, _width = 720) {
  if (!imageUrl || typeof imageUrl !== 'string') return imageUrl;
  return imageUrl.trim();
}

let boutiqueImageWarmPromise = null;

/** Prefetch catalog thumbs (+ a few gallery frames) into expo-image cache. */
export function warmBoutiqueCatalogImages() {
  if (boutiqueImageWarmPromise) return boutiqueImageWarmPromise;
  const uris = [];
  BOUTIQUE_PRODUCTS.forEach((product) => {
    const images = getBoutiqueProductImages(product);
    images.slice(0, 4).forEach((uri) => {
      if (uri && !uris.includes(uri)) uris.push(uri);
    });
  });
  boutiqueImageWarmPromise = Promise.all(
    uris.map((uri) => Image.prefetch(uri).catch(() => false)),
  ).catch(() => []);
  return boutiqueImageWarmPromise;
}

export function resetBoutiqueImageWarm() {
  boutiqueImageWarmPromise = null;
}
